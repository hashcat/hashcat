sub module_constraints { [[9, 100], [1, 8], [-1, -1], [-1, -1], [-1, -1]] }

sub ibm_des_crypt
{
  my ($plaintext, $key_bytes) = @_;

  my @mangled;

  for (my $i = 0; $i < 8; $i++)
  {
    $mangled[$i] = (($key_bytes->[$i] ^ 0x55) << 1) & 0xfe;
  }

  my $key = pack ("C8", @mangled);

  my $cipher = Crypt::DES->new ($key);

  return $cipher->encrypt ($plaintext);
}

sub module_generate_hash
{
  my $word = shift;
  my $salt = shift;

  if (! defined $salt)
  {
    my $ulen = 1 + int (rand (8));
    $salt = "";
    for (my $i = 0; $i < $ulen; $i++)
    {
      $salt .= chr (0x41 + int (rand (26)));
    }
  }

  my $pw_len = length ($word);

  my @user = (0x40) x 8;
  for (my $i = 0; $i < length ($salt); $i++)
  {
    $user[$i] = $a2e_up[ord (substr ($salt, $i, 1))];
  }
  my $user_packed = pack ("C8", @user);

  my $num_blocks = int (($pw_len + 7) / 8);
  my @pw_ebcdic = (0x40) x ($num_blocks * 8);
  for (my $i = 0; $i < $pw_len; $i++)
  {
    $pw_ebcdic[$i] = $a2e[ord (substr ($word, $i, 1))];
  }

  my @out = (0) x 8;
  my $full_hash = "";

  for (my $block = 0; $block < $num_blocks; $block++)
  {
    my @key_block;
    for (my $j = 0; $j < 8; $j++)
    {
      $key_block[$j] = $pw_ebcdic[$block * 8 + $j] ^ $out[$j];
    }

    my $ciphertext = ibm_des_crypt ($user_packed, \@key_block);

    @out = unpack ("C8", $ciphertext);
    $full_hash .= $ciphertext;
  }

  $full_hash = substr ($full_hash, 0, $pw_len);

  my $hex_hash = uc (unpack ("H*", $full_hash));

  my $hash = sprintf ("%s*%s", uc ($salt), $hex_hash);

  return $hash;
}

sub module_verify_hash
{
  my $line = shift;

  my ($hash_in, $word) = split (/:/, $line);

  return unless defined $hash_in;
  return unless defined $word;

  my ($username, $hex_hash) = split (/\*/, $hash_in);

  return unless defined $username;
  return unless defined $hex_hash;

  $word = pack_if_HEX_notation ($word);

  my $new_hash = module_generate_hash ($word, $username);

  return ($new_hash, $word);
}

