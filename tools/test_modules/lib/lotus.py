B64 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+/"


def _mix(x):
  p = 0

  for _ in range(18):
    for j in range(48):
      p = (p + 48 - j) & 0xff
      p = x[j] ^ MAGIC[p]
      x[j] = p


def _transform_norecalc(state, block):
  x = state + block + [state[i] ^ block[i] for i in range(16)]

  _mix(x)

  state[:] = x[:16]


def _transform_password(block, out):
  t = out[15]

  for i in range(16):
    t ^= block[i]
    out[i] ^= MAGIC[t]
    t = out[i]


def big_md(key, size=None):
  # key is a list of byte values; returns the 16 byte state as a list. size, when given, is how many
  # of the key bytes to process, which Domino fixes at 34 for the salted second pass.

  if size is None:
    size = len(key)

  key = key[:size]

  state = [0] * 16
  checksum = [0] * 16

  pos = 0

  while pos + 16 < size:
    block = key[pos:pos + 16]
    _transform_norecalc(state, block)
    _transform_password(block, checksum)
    pos += 16

  left = size - pos
  block = key[pos:pos + 16]
  block += [16 - left] * (16 - len(block))

  _transform_norecalc(state, block)
  _transform_password(block, checksum)
  _transform_norecalc(state, checksum)

  return state


def base64_encode(v, n):
  out = ""

  for _ in range(n):
    out = B64[v & 0x3f] + out
    v >>= 6

  return out


def base64_decode(s, n):
  # perl's substr () past the end gives "", and index (table, "") is 0, so a group shorter than n
  # counts its missing positions as 0 rather than raising

  ret = 0

  for i in range(1, n + 1):
    pos = n - i
    c = s[pos] if pos < len(s) else ""
    ret += ((B64.index(c) if c else 0) & 0x3f) << (6 * (i - 1))

  return ret


def encode(final, char):
  # final is a byte string; returns the Domino base64 account string

  b = bytearray(final)

  b[3] = (b[3] + 4) & 0xff

  out = ""

  for i in range(0, 15, 3):
    out += base64_encode((b[i] << 16) | (b[i + 1] << 8) | b[i + 2], 4)

  if char is not None:
    out = out[:18] + char + out[19:]

  return out[:19]


def decode(s):
  raw = bytearray()

  for i in range(0, len(s), 4):
    num = base64_decode(s[i:i + 4], 4)
    raw += bytes(((num >> 16) & 0xff, (num >> 8) & 0xff, num & 0xff))

  salt = bytearray(raw[0:5])
  salt[3] = (salt[3] - 4) & 0xff

  return (bytes(raw[5:14]), bytes(salt), s[18] if len(s) > 18 else None)
