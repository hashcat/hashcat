sub module_constraints { [[9, 100], [-1, -1], [-1, -1], [-1, -1], [-1, -1]] }

sub pbkdf2_sha256_racf
{
  my ($key, $salt, $iterations) = @_;

  my $dk = hmac_sha256 ($salt . pack ("N", 1), $key);
  my $u  = $dk;
  my $newsalt = "";

  for (my $i = 1; $i < $iterations; $i++)
  {
    $u = hmac_sha256 ($u, $key);
    $dk ^= $u;

    if ($i == $iterations - 2)
    {
      $newsalt = substr ($u, 0, 16);
    }
  }

  return ($dk, $newsalt);
}

sub module_generate_hash
{
  my $word = shift;
  my $salt = shift;

  my $rfactor = 8;
  my $rounds  = 50;
  my $random_salt;

  if (! defined $salt)
  {
    $random_salt = pack ("H*", "00112233445566778899AABBCCDDEEFF");
    $salt = "HASHCAT";
  }
  else
  {
    my ($sig, $user, $header_hex, $salt_hex, $hash_hex) = split (/\*/, $salt);
    $salt = $user;
    $random_salt = pack ("H*", $salt_hex);

    my $mf = hex (substr ($header_hex, 18, 2));
    my $rf = hex (substr ($header_hex, 20, 4));
    $rfactor = $mf;
    $rounds  = $rf;
  }

  my $pw_len = length ($word);
  my $loops = 2 ** ($rfactor - 5);
  my $iterations = $rounds * 100;

  my $ebcdic_pw = "";
  for (my $i = 0; $i < $pw_len; $i++)
  {
    $ebcdic_pw .= chr ($a2e[ord (substr ($word, $i, 1))]);
  }

  my $K = sha256 ($ebcdic_pw);
  $K .= "\x00" x 7;
  $K .= chr ($pw_len * 8);

  my $ebcdic_user = "";
  for (my $i = 0; $i < length ($salt); $i++)
  {
    $ebcdic_user .= chr ($a2e[ord (uc (substr ($salt, $i, 1)))]);
  }
  for (my $i = length ($salt); $i < 8; $i++)
  {
    $ebcdic_user .= chr (0x40);
  }

  my @acc;
  my $cursalt = $random_salt . pack ("N", $loops);

  for (my $cnt = 0; $cnt < $loops; $cnt++)
  {
    my ($tmp_hash, $newsalt) = pbkdf2_sha256_racf ($K, $cursalt, $iterations);
    $acc[$cnt] = $tmp_hash;
    $cursalt = $newsalt . $tmp_hash;
  }

  my $md = $acc[$loops - 1];

  for (my $i = 0; $i < $loops; $i++)
  {
    my $id = ord (substr ($md, 31, 1)) & ($loops - 1);
    ($md, undef) = pbkdf2_sha256_racf ($md, $acc[$id], 1);
    $acc[$i] = $md;
  }

  my $combined_salt = "";
  for (my $i = 0; $i < $loops - 1; $i++)
  {
    $combined_salt .= $acc[$i];
  }

  my ($aes_key, $ns) = pbkdf2_sha256_racf ($md, $combined_salt, $iterations);

  my $user_padded = $ebcdic_user . ("\x00" x 24);

  my $aes = Crypt::Mode::ECB->new ('AES', 0);
  my $cipher_text = $aes->encrypt (substr ($user_padded, 0, 16), $aes_key);

  my $hash_hex = uc (unpack ("H*", $cipher_text));

  my $header = sprintf ("E7D7E66D0001400000%02X%04X00100010", $rfactor, $rounds);

  my $hash = sprintf ("\$racf-kdfaes\$*%s*%s*%s*%s",
    uc ($salt),
    $header,
    uc (unpack ("H*", $random_salt)),
    $hash_hex);

  return $hash;
}

sub module_verify_hash
{
  my $line = shift;

  my ($hash_in, $word) = split (/:/, $line);

  return unless defined $hash_in;
  return unless defined $word;

  $word = pack_if_HEX_notation ($word);

  my @parts = split (/\*/, $hash_in);
  return unless scalar @parts == 5;

  my $salt = join ("*", @parts);

  my $new_hash = module_generate_hash ($word, $salt);

  return ($new_hash, $word);
}

