DEFAULT_VARIANT = "2.13a"

BOARD_SHAPE = {
    "din_bits":       32,

    "init_batch":     0,

    "num_cores_dist": 4,

    "feed_group":     0,

    "feed_shard":     0,

    "collect_group":  0,

    "no_dump":        1,

    "no_cmp":         0,
}

VCO_MIN_MHZ = 600.0
VCO_MAX_MHZ = 1200.0

FXCLK_MHZ = 48.0

def mmcm_recipe_c2 (fin_mhz, fout_mhz):
    best = None

    centre = (VCO_MIN_MHZ + VCO_MAX_MHZ) / 2.0

    for divclk in range (1, 5):
        for mult8 in range (16, 513):
            vco = fin_mhz * (mult8 / 8.0) / divclk

            if (vco < VCO_MIN_MHZ) or (vco > VCO_MAX_MHZ): continue
            for out1div in range (1, 64):
                if abs (vco / (2 * out1div) - fout_mhz) > 1e-9: continue
                key = (divclk, abs (vco - centre))
                if (best is None) or (key < best[0]):
                    best = (key, (divclk, mult8 * 125, 2 * out1div * 1000, out1div))
    if best is None: return None
    recipe = best[1]

    return recipe

def mmcm_recipe (fin_mhz, fout_mhz):
    best = None
    centre = (VCO_MIN_MHZ + VCO_MAX_MHZ) / 2.0

    for divclk in range (1, 107):
        for mult8 in range (2 * 8, 64 * 8 + 1):
            mult = mult8 / 8.0
            vco  = fin_mhz * mult / divclk
            if vco < VCO_MIN_MHZ: continue
            if vco > VCO_MAX_MHZ: continue

            out8 = round (vco / fout_mhz * 8.0)
            if out8 < 8:         continue
            if out8 > 128 * 8:   continue
            out = out8 / 8.0
            if abs (vco / out - fout_mhz) > 1e-9: continue

            fracs = (0 if mult8 % 8 == 0 else 1) + (0 if out8 % 8 == 0 else 1)
            if fracs > 1: continue

            key = (divclk, abs (vco - centre), fracs)

            if best is None or key < best[0]:
                best = (key, (divclk, int (round (mult * 1000)), int (round (out * 1000))))
    if best is None: return None
    return best[1]

HERE     = os.path.dirname (os.path.abspath (__file__))
GATEWARE = os.path.join (HERE, "gateware")
BCRYPT   = os.path.join (GATEWARE, "bcrypt")
CORE     = os.path.join (BCRYPT, "bcrypt_core")
SHELL    = os.path.join (GATEWARE, "ztex_fx2")

DATAPATH_SV = [os.path.join (BCRYPT, "hcfpga_top.sv")]

DATAPATH_V = [os.path.join (BCRYPT, f) for f in
              ["hcfpga_feed.v", "hcfpga_feed_group.v", "hcfpga_cores.v", "hcfpga_result_filter.v", "hcfpga_collect.v", "hcfpga_collect_group.v"]] + \
             [os.path.join (CORE, f) for f in
              ["bcrypt_core.v", "bcrypt_core_c2.v", "fsm.v", "unit.v", "addr_regs.v", "P_2x32.v", "S.v"]]
SHELL_V = [os.path.join (SHELL, f) for f in
           ["hcfpga_ztex_top.v", "hcfpga_ztex_regs.v", "hcfpga_ztex_temp.v", "hcfpga_ztex_afifo.v", "ezusb_io.v", "ezusb_lsi.v"]]

XDC = os.path.join (HERE, "platforms", "usb_fpga_2.13.xdc")
INCLUDE_DIRS = [SHELL, BCRYPT, CORE, HERE]

def tcl_list (paths):
    return " ".join ("{%s}" % p for p in paths)
def write_tcl (path, build_dir, name, part, generics, threads, place_directive):
    lines = []

    lines.append ("# Generated by bcrypt_ztex213_usb.py. Do not edit: rebuild instead.")
    lines.append ("")
    lines.append ("set_param general.maxThreads %d" % min (threads, 32))
    lines.append ("")
    for f in DATAPATH_SV:
        lines.append ("read_verilog -sv {%s}" % f)
    for f in SHELL_V + DATAPATH_V:
        lines.append ("read_verilog {%s}" % f)
    lines.append ("")
    lines.append ("read_xdc {%s}" % XDC)
    lines.append ("")

    gen = " ".join ("-generic %s=%s" % (k, v) for k, v in generics.items ())

    lines.append ("synth_design -top hcfpga_ztex_top -part %s \\" % part)
    lines.append ("  -include_dirs {%s} \\" % " ".join (INCLUDE_DIRS))
    lines.append ("  -directive PerformanceOptimized \\")
    lines.append ("  %s" % gen)
    lines.append ("")

    lines.append ("set mmcms [get_cells -hier -filter {REF_NAME == MMCME2_ADV || REF_NAME == MMCME2_BASE}]")
    lines.append ("if {[llength $mmcms] != 2} {")
    lines.append ("  error \"hcfpga: expected exactly two MMCMs, the core clock and ezusb_io's, found [llength $mmcms]: $mmcms\"")
    lines.append ("}")
    lines.append ("")
    lines.append ("set core_mmcm {}")
    lines.append ("set if_mmcm {}")
    lines.append ("foreach m $mmcms {")
    lines.append ("  if {[string match {*core_mmcm*} $m]} { set core_mmcm $m } else { set if_mmcm $m }")
    lines.append ("}")
    lines.append ("if {$core_mmcm eq {} || $if_mmcm eq {}} {")
    lines.append ("  error \"hcfpga: could not tell the two MMCMs apart by name: $mmcms\"")
    lines.append ("}")
    lines.append ("")
    lines.append ("set_property LOC MMCME2_ADV_X0Y0 [get_cells $if_mmcm]")
    lines.append ("set_property LOC MMCME2_ADV_X0Y1 [get_cells $core_mmcm]")
    lines.append ("")
    lines.append ("set fxbuf [get_nets -of_objects [get_pins -of_objects [get_cells $core_mmcm] -filter {REF_PIN_NAME == CLKIN1}]]")
    lines.append ("if {[llength $fxbuf] != 1} {")
    lines.append ("  error \"hcfpga: expected one net on the core MMCM's CLKIN1, found [llength $fxbuf]\"")
    lines.append ("}")
    lines.append ("set_property CLOCK_DEDICATED_ROUTE BACKBONE $fxbuf")
    lines.append ("puts \"hcfpga: core MMCM $core_mmcm at X0Y1 on a backbone route, ezusb_io's $if_mmcm at X0Y0 dedicated\"")
    lines.append ("")
    lines.append ("set core_clk [get_clocks -of_objects [get_pins -hier -filter {NAME =~ *core_mmcm/CLKOUT0}]]")
    lines.append ("if {[llength $core_clk] != 1} {")
    lines.append ("  error \"hcfpga: expected exactly one core clock off core_mmcm/CLKOUT0, found [llength $core_clk]\"")
    lines.append ("}")
    lines.append ("")
    lines.append ("set core_period [get_property PERIOD $core_clk]")
    lines.append ("puts \"hcfpga: core clock [get_property NAME $core_clk], period $core_period ns\"")
    lines.append ("")
    lines.append ("set if_period [get_property PERIOD [get_clocks ifclk_in]]")
    lines.append ("set skew_bound [expr {min ($core_period, $if_period)}]")
    lines.append ("")
    for fifo in ("in_fifo", "out_fifo"):
        for ptr in ("wr", "rd"):
            lines.append ("set src [get_cells -hier -regexp {.*%s/%s_gray_reg\\[.*\\]}]" % (fifo, ptr))
            lines.append ("set dst [get_cells -hier -regexp {.*%s/%s_gray_meta_reg\\[.*\\]}]" % (fifo, ptr))
            lines.append ("if {[llength $src] == 0 || [llength $dst] == 0} {")
            lines.append ("  error \"hcfpga: the %s %s pointer matched [llength $src] sources and [llength $dst] destinations, so it would have been left unconstrained\"" % (fifo, ptr))
            lines.append ("}")
            lines.append ("set_bus_skew -from $src -to $dst $skew_bound")
    lines.append ("")
    lines.append ("set cfg_src [get_cells -hier -regexp {.*regs/(salt[0-3]|iter_count|ctrl|cmp_bitmap|batch_target|pad_recs|cfg_kind)_reg\\[.*\\]}]")
    lines.append ("set cfg_dst [get_cells -hier -regexp {.*core_(salt[0-3]|iter_count|mode_dump|cmp_bitmap|batch_target|pad_recs|cmp_load|batch_arm)_reg(\\[.*\\])?}]")
    lines.append ("set tog_src [get_cells -hier -regexp {.*regs/cfg_toggle_reg}]")
    lines.append ("set tog_dst [get_cells -hier -regexp {.*cfg_tog_q_reg\\[0\\]}]")
    lines.append ("if {[llength $cfg_src] == 0 || [llength $cfg_dst] == 0 || [llength $tog_src] == 0 || [llength $tog_dst] == 0} {")
    lines.append ("  error \"hcfpga: the configuration crossing matched [llength $cfg_src] -> [llength $cfg_dst] flops and its toggle [llength $tog_src] -> [llength $tog_dst], so it would have been left unconstrained\"")
    lines.append ("}")
    lines.append ("puts \"hcfpga: configuration crossing [llength $cfg_src] -> [llength $cfg_dst] flops, bounded against its toggle\"")
    lines.append ("set_bus_skew -from [concat $cfg_src $tog_src] -to [concat $cfg_dst $tog_dst] $core_period")
    lines.append ("")
    lines.append ("opt_design")
    lines.append ("place_design -directive %s" % place_directive)
    lines.append ("phys_opt_design -directive AggressiveExplore")
    lines.append ("route_design -directive AggressiveExplore")
    lines.append ("phys_opt_design -directive AggressiveExplore")
    lines.append ("")
    lines.append ("report_utilization -file {%s}" % os.path.join (build_dir, name + "_utilization.rpt"))
    lines.append ("report_timing_summary -file {%s}" % os.path.join (build_dir, name + "_timing.rpt"))
    lines.append ("")
    lines.append ("set wns [get_property SLACK [get_timing_paths -delay_type min_max]]")
    lines.append ("puts \"hcfpga: WNS $wns ns\"")
    lines.append ("if {$wns < 0} {")
    lines.append ("  error \"hcfpga: timing FAILED, WNS $wns ns. No bitstream written. Lower --sys-clk-freq or --cores.\"")
    lines.append ("}")
    lines.append ("")
    lines.append ("report_bus_skew -file {%s}" % os.path.join (build_dir, name + "_bus_skew.rpt"))
    lines.append ("set skew_rpt [report_bus_skew -return_string]")
    lines.append ("set skew_neg [regexp -all -line {^\\s+(Slow|Fast)\\s+[-0-9.]+\\s+[-0-9.]+\\s+-[0-9.]+\\s*$} $skew_rpt]")
    lines.append ("if {[string match {*VIOLATED*} $skew_rpt] || ($skew_neg > 0)} {")
    lines.append ("  error \"hcfpga: bus skew FAILED on a clock crossing. No bitstream written. See %s_bus_skew.rpt\"" % name)
    lines.append ("}")
    lines.append ("")
    lines.append ("write_bitstream -force {%s}" % os.path.join (build_dir, "gateware", name + ".bit"))
    with open (path, "w") as f:
        f.write ("\n".join (lines) + "\n")
def main ():
    parser = argparse.ArgumentParser (description = "hcfpga bcrypt on a ZTEX USB-FPGA Module 2.13.")

    parser.add_argument ("--build", action = "store_true", help = "Build the bitstream.")
    parser.add_argument ("--load",  action = "store_true", help = "Accepted and does nothing. This board is programmed over USB by hashcat at every run.")
    parser.add_argument ("--variant", type = str, default = DEFAULT_VARIANT, choices = sorted (PARTS), help = "Which 2.13 is fitted. They differ only in the part.")
    parser.add_argument ("--cores", type = int, default = 24, help = "Number of bcrypt cores. 24 with 4 distributed is what fits beside the shell on a 2.13a.")

    parser.add_argument ("--no-dump", action = "store_true", help = "Leave the unfinished S state dump path out of the cores. This board declares it, see BOARD_SHAPE.")
    parser.add_argument ("--no-cmp",  action = "store_true", help = "Build the array without the per-core comparator. About 30 LUTs a core, and this is the smallest part in the tree, so it is the one that might not fit. Wire compatible either way.")
    parser.add_argument ("--din-bits",       type = int, default = BOARD_SHAPE["din_bits"],       help = "Width of the feeder-to-core bus, 8 or 32.")
    parser.add_argument ("--feed-group",     type = int, default = BOARD_SHAPE["feed_group"],     help = "Cores per fanout group on the feeder bus. 0 is the original single hop.")
    parser.add_argument ("--feed-shard",     type = int, default = BOARD_SHAPE["feed_shard"],     help = "Cores per feeder engine. The feeder serves cores one at a time, so the lap in front of a core is the array's fixed per-candidate cost. Must be a multiple of --feed-group. 0 is one feeder over the whole array.")
    parser.add_argument ("--collect-group",  type = int, default = BOARD_SHAPE["collect_group"],  help = "Cores per collector engine. 0 is one engine over the whole array.")
    parser.add_argument ("--num-cores-dist", type = int, default = BOARD_SHAPE["num_cores_dist"], help = "How many cores keep their S-boxes in distributed RAM. This part needs 4.")
    parser.add_argument ("--init-batch",     type = int, default = BOARD_SHAPE["init_batch"],     help = "How many cores must be waiting before an init broadcast is sent.")
    parser.add_argument ("--sys-clk-freq", type = float, default = 100e6, help = "Core clock (Hz). Must be exactly reachable from the board's 48 MHz.")

    parser.add_argument ("--in-addr-bits",  type = int, default = 9, help = "Inbound crossing depth, 1 << N words of 32 bits. 9 is 2 KB, or 16 candidate records.")
    parser.add_argument ("--out-addr-bits", type = int, default = 8, help = "Outbound crossing depth, 1 << N words of 16 bits. 8 is 512 bytes, or 16 result frames.")

    parser.add_argument ("--threads", type = int, default = os.cpu_count (), help = "Vivado threads.")
    parser.add_argument ("--place-directive", type = str, default = "ExtraTimingOpt", help = "Vivado placer directive. The default is what every published bitstream for this board was built with, so a plain build reproduces it exactly. Exposed so a shape that misses by tens of picoseconds can be swept without editing the file.")
    parser.add_argument ("--abi", type = int, default = fpga_abi_current (), help = "Wire version reported at REG_ABI. Taken from FPGA_ABI_CURRENT in the bridge header, which is where src/fpga/Makefile takes it from as well, so it is never written down twice and running this script by hand builds the same wire version.")
    parser.add_argument ("--cslow", type = int, default = 1, choices = [1, 2], help = "2 builds the array from bcrypt_core_c2 on a second clock at twice --sys-clk-freq, two virtual cores to a physical one. --cores then counts virtual cores.")
    parser.add_argument ("--startup-clk", type = str, default = "Cclk", choices = ["Cclk", "JtagClk"], help = "PL startup clock. Cclk is the only one this board can be programmed with.")
    args = parser.parse_args ()
    if args.startup_clk != "Cclk":
        print ("  --startup-clk JtagClk: this board has no JTAG. The FX2 clocks the bitstream in over")
        print ("  the high speed configuration endpoint, which is the Cclk path, so a JtagClk build")
        print ("  would configure and then never assert DONE.")
        return 1
    mhz = int (args.sys_clk_freq / 1e6)
    if abs (args.sys_clk_freq - mhz * 1e6) > 1.0:
        print ("  --sys-clk-freq must be a whole number of MHz, the identity register reports MHz.")

        return 1
    out1div = 0

    if args.cslow == 2:
        recipe_c2 = mmcm_recipe_c2 (FXCLK_MHZ, float (mhz))
        recipe = None if (recipe_c2 is None) else recipe_c2[0:3]
        if recipe_c2 is not None: out1div = recipe_c2[3]
    else:
        recipe = mmcm_recipe (FXCLK_MHZ, float (mhz))

    if recipe is None:
        print ("  %d MHz is not reachable from this board's %g MHz fxclk with one MMCM." % (mhz, FXCLK_MHZ))
        print ("  Nearby frequencies that are:")
        search = mmcm_recipe_c2 if (args.cslow == 2) else mmcm_recipe
        for cand in range (60, 201):
            if search (FXCLK_MHZ, float (cand)) is not None: print ("    %d" % cand, end = "")

        print ()
        return 1
    divclk, mult_milli, outdiv_milli = recipe
    part = PARTS[args.variant]
    with_dump = 0 if args.no_dump else 1
    with_cmp  = 0 if args.no_cmp  else 1
    fg_suffix = "" if args.feed_group     == 0 else "_fg%d" % args.feed_group
    nd_suffix = "_nodump" if args.no_dump else ""
    nc_suffix = "_nocmp"  if args.no_cmp  else ""
    db_suffix = "" if args.din_bits       == 8 else "_din%d" % args.din_bits
    ds_suffix = "" if args.num_cores_dist == 0 else "_d%d" % args.num_cores_dist
    fs_suffix = "" if args.feed_shard     == 0 else "_fs%d" % args.feed_shard
    cg_suffix = "" if args.collect_group  == 0 else "_cg%d" % args.collect_group
    ib_suffix = "" if args.init_batch     == 0 else "_ib%d" % args.init_batch
    pd_suffix = "" if args.place_directive == "ExtraTimingOpt" else "_p%s" % args.place_directive
    if args.cslow == 2: pd_suffix += "_cs2"
    fb_suffix = ""
    if args.in_addr_bits  != 9: fb_suffix += "_if%d" % args.in_addr_bits
    if args.out_addr_bits != 8: fb_suffix += "_of%d" % args.out_addr_bits
    name = "bcrypt_%s_usb_c%d_%dmhz_cclk%s%s%s%s%s%s%s%s%s%s" % (
        BOARD, args.cores, mhz, fg_suffix, nd_suffix, nc_suffix, db_suffix, ds_suffix, fs_suffix, cg_suffix, ib_suffix, fb_suffix, pd_suffix)
    build_dir = os.path.join (HERE, "build", name)
    os.makedirs (os.path.join (build_dir, "gateware"), exist_ok = True)
    stamp = int (datetime.datetime.now ().timestamp ())
    generics = {
        "NUM_CORES":         args.cores,
        "NUM_CORES_DIST":    args.num_cores_dist,
        "INIT_BATCH":        args.init_batch,
        "DIN_BITS":          args.din_bits,
        "FEED_GROUP":        args.feed_group,
        "FEED_SHARD":        args.feed_shard,
        "COLLECT_GROUP":     args.collect_group,
        "WITH_DUMP":         with_dump,
        "WITH_CMP":          with_cmp,
        "CORE_CLK_MHZ":      mhz,
        "MMCM_DIVCLK":       divclk,
        "MMCM_MULT_MILLI":   mult_milli,
        "MMCM_OUTDIV_MILLI": outdiv_milli,
        "BUILD_STAMP":       stamp,
        "ABI_VERSION":       args.abi,
        "IN_ADDR_BITS":      args.in_addr_bits,
        "OUT_ADDR_BITS":     args.out_addr_bits,
        "CSLOW":             args.cslow,
        "MMCM_OUT1DIV":      out1div if (args.cslow == 2) else 4,
    }
    tcl = os.path.join (build_dir, name + ".tcl")
    write_tcl (tcl, build_dir, name, part, generics, args.threads, args.place_directive)
    print ("  %s on %s (%s)" % (name, part, args.variant))
    print ("  core clock %d MHz: DIVCLK %d, MULT %.3f, CLKOUT0 %.3f, VCO %.3f MHz" % (
        mhz, divclk, mult_milli / 1000.0, outdiv_milli / 1000.0,
        FXCLK_MHZ * (mult_milli / 1000.0) / divclk))
    if args.cslow == 2:
        print ("  that is the fabric clock: the two hash cores run at %d MHz off CLKOUT1 %d" % (2 * mhz, out1div))
    print ("  tcl %s" % tcl)
    if args.load:
        bit = os.path.join (build_dir, "gateware", name + ".bit")
        print ()
        print ("  This script does not load the board. Its fabric is volatile, and hashcat uploads the bitstream")
        print ("  over USB at the start of every run, so it has to be installed where the bridge looks")
        print ("  rather than pushed at the board from here:")
        print ()
        print ("    mkdir -p ~/.local/share/hashcat/fpga")
        print ("    cp %s ~/.local/share/hashcat/fpga/bcrypt-%s.bit" % (bit, BOARD))
        print ()
        print ("  That is the directory of an installed hashcat. A build tree reads fpga/ beside the hashcat")
        print ("  binary instead. hashcat prints the directories it searches, see docs/hashcat-fpga-setup.md.")
        print ()
        return 0
    if not args.build: return 0
    print ()

    log = os.path.join (build_dir, name + ".log")
    rc = subprocess.call (["vivado", "-mode", "batch", "-nojournal",
                           "-log", log, "-source", tcl],
                          cwd = build_dir)
    if rc != 0:
        print ()
        print ("  vivado exited %d. Log: %s" % (rc, log))
        return rc
    return 0
if __name__ == "__main__":
    sys.exit (main ())
