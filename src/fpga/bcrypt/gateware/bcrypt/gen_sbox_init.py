import sys

def main() -> int:
  if len(sys.argv) != 3:
    sys.stderr.write("usage: gen_sbox_init.py <S_data.txt> <out.vh>\n")
    return 2

  src = sys.argv[1]
  dst = sys.argv[2]

  words = []

  with open(src) as f:
    for line in f:
      line = line.strip()

      if line == "":
        continue

      if line.startswith("//"):
        continue

      words.append(int(line, 16))

  if len(words) != 1024:
    sys.stderr.write("%s holds %d words, expected 1024\n" % (src, len(words)))
    return 1

  base = 30

  with open(dst, "w") as f:
    f.write("//\n")
    f.write("// Author......: See docs/credits.txt\n")
    f.write("// License.....: MIT\n")
    f.write("//\n")
    f.write("// GENERATED by gen_sbox_init.py from %s. Do not edit.\n" % src)
    f.write("//\n")
    f.write("// The Blowfish S-box constants, as literal assignments into hcfpga_feed's init image.\n")
    f.write("// See the generator for why this is not a $readmemh.\n")
    f.write("//\n")
    f.write("\n")

    for i in range(0, 1024, 4):
      cols = []

      for j in range(4):
        cols.append("initimg[%4d]=32'h%08x;" % (base + i + j, words[i + j]))

      f.write(" ".join(cols) + "\n")

  sys.stdout.write("wrote %s, %d words at initimg[%d..%d]\n" % (dst, len(words), base, base + 1023))

  return 0

if __name__ == "__main__":
  sys.exit(main())
