import os
import sys

sys.path.insert (0, os.path.join (os.path.dirname (os.path.abspath (__file__)), 'bcrypt_core'))

import bcrypt_ref

SALT4  = [0x00010203, 0x04050607, 0x08090a0b, 0x0c0d0e0f]
ROUNDS = 1

PWS = [
  b'',
  b'a',
  b'abc',
  b'abcd',
  b'password',
  b'hello world',
  bytes ((0x41 + (i % 26)) for i in range (71)),
  bytes ((0x41 + (i % 26)) for i in range (72)),
]

def expand_key (pw):
  n   = len (pw)
  cyc = n + 1
  out = []
  idx = 0
  for _ in range (18):
    val = 0
    for _ in range (4):
      c = pw[idx] if idx < n else 0
      val = ((val << 8) | c) & 0xffffffff
      idx += 1
      if idx >= cyc:
        idx = 0
    out.append (val)
  return out
def main ():
  here = os.path.dirname (os.path.abspath (__file__))
  s_path = os.path.join (here, 'S_data.txt')
  print ('//')
  print ('// GENERATED by gen_expand_vectors.py. Do not edit.')
  print ('//')
  print ('// %d passwords, their lengths, their bytes packed four to a word, and the digest each one' % len (PWS))
  print ('// produces at rounds = %d against salt %s.' % (ROUNDS, ' '.join ('%08x' % s for s in SALT4)))
  print ('//')
  print ('initial begin')
  for i, pw in enumerate (PWS):
    ek18 = expand_key (pw)
    _, _, ct = bcrypt_ref.run (s_path, ek18, SALT4, ROUNDS)
    padded = pw + (b'\x00' * ((4 - (len (pw) % 4)) % 4))
    words = [int.from_bytes (padded[4*k:4*k+4], 'big') for k in range (len (padded) // 4)]
    print ('  // %2d  len %2d  %s' % (i, len (pw), repr (pw)))
    print ('  pwlen[%d] = %d;' % (i, len (pw)))
    for k, w in enumerate (words):
      print ('  pwbuf[%d][%2d] = 32\'h%08x;' % (i, k, w))
    digest = b''.join (c.to_bytes (4, 'big') for c in ct)
    for k in range (24):
      print ('  gold[%d][%2d] = 8\'h%02x;' % (i, k, digest[k]))
    print ('')
  print ('end')
  return 0
if __name__ == '__main__':
  sys.exit (main ())
