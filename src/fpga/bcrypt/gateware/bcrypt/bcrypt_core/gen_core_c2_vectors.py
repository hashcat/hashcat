import os
import sys

sys.path.insert (0, os.path.dirname (os.path.abspath (__file__)))

import bcrypt_ref

CANDS = [
  (b'password', [0x00010203, 0x04050607, 0x08090a0b, 0x0c0d0e0f], 0xdeadbeef),
  (b'hashcat!', [0x10111213, 0x14151617, 0x18191a1b, 0x1c1d1e1f], 0x0badf00d),
]

TB_CORE_GOLD = [0xcff8a8ac, 0x7bdadd00, 0x1b00d26d, 0xf3c9e4ed, 0x0c4983e3, 0x981b1d0d]

def ek18 (pw):
  key = pw + b'\x00'

  stream = bytes (key[i % len (key)] for i in range (72))

  words = [int.from_bytes (stream[4*i:4*i+4], 'big') for i in range (18)]

  return words

def main ():
  s_path = os.path.join (os.path.dirname (os.path.abspath (__file__)), 'S_data.txt')

  lines = []

  lines.append ('//')
  lines.append ('// GENERATED by gen_core_c2_vectors.py. Do not edit.')
  lines.append ('//')
  lines.append ('// Two data batches for tb_core_c2.v, one per virtual core, and the digest each must produce at')
  lines.append ('// cost 5. Included inside the bench\'s initial block, so this is statements only.')
  lines.append ('//')

  for v, (pw, salt, ekid) in enumerate (CANDS):
    P, S, ct = bcrypt_ref.run (s_path, ek18 (pw), salt, 32)

    if (v == 0) and (ct != TB_CORE_GOLD):
      sys.exit ('bcrypt_ref.py does not reproduce the tb_core golden digest, refusing to write vectors')

    words = ek18 (pw) + [64, 32] + salt + [ekid, 0] + [0] * 5

    lines.append ('')
    lines.append ('    // virtual core %d: %s' % (v, pw.decode ()))

    for i, w in enumerate (words):
      lines.append ("    batch[%d][%2d] = 32'h%08x;" % (v, i, w))

    for i, c in enumerate (ct):
      lines.append ("    gold[%d][%d] = 32'h%08x;" % (v, i, c))

    lines.append ("    ekid[%d] = 32'h%08x;" % (v, ekid))

  print ('\n'.join (lines))

  return 0

if __name__ == '__main__':
  sys.exit (main ())
