import os
import sys
import zlib

def main ():
    if len (sys.argv) not in (3, 4):
        print ("usage: gen_ps_app.py <app.bin> <out.h> [compiler-identity]", file = sys.stderr)

        return 1

    src = sys.argv[1]
    dst = sys.argv[2]

    cc = sys.argv[3] if len (sys.argv) == 4 else "unrecorded"

    with open (src, "rb") as f:
        img = f.read ()

    if len (img) == 0:
        print ("gen_ps_app: %s is empty" % src, file = sys.stderr)

        return 1

    first = int.from_bytes (img[0:4], "little")

    if (first & 0xFF000000) != 0xEA000000:
        print ("gen_ps_app: %s does not start with an ARM branch, first word is 0x%08X" % (src, first), file = sys.stderr)

        return 1

    lines = []

    lines.append ("/**")
    lines.append (" * Author......: See docs/credits.txt")
    lines.append (" * License.....: MIT")
    lines.append (" */")
    lines.append ("//")
    lines.append ("// The bare metal application this board runs, as data.")
    lines.append ("//")
    lines.append ("// GENERATED by src/fpga/bcrypt/ps_app/gen_ps_app.py. Do not edit.")
    lines.append ("//")
    lines.append ("// It is carried here rather than shipped as a file because it implements the wire protocol the")
    lines.append ("// transport speaks. The two have to version together, and a separate file lets them drift.")
    lines.append ("//")
    lines.append ("// Built by: %s" % cc)
    lines.append ("//")
    lines.append ("// That line is provenance rather than a requirement. Any bare metal ARM cross compiler builds")
    lines.append ("// this image, and a different one gives a different size for the same sources. 'make -C src/fpga")
    lines.append ("// check-ps-app' rebuilds it and compares, and it only demands the bytes match when the compiler")
    lines.append ("// on the path is the one named above.")
    lines.append ("")
    lines.append ("#ifndef HC_ARTYZ7_PS_APP_H")
    lines.append ("#define HC_ARTYZ7_PS_APP_H")
    lines.append ("")
    lines.append ("#include <stdint.h>")
    lines.append ("")
    lines.append ("#define ARTYZ7_PS_APP_SIZE %u" % len (img))
    lines.append ("")
    lines.append ("// CRC-32 of the image, the value the application reports in its ping reply. A board answering")
    lines.append ("// with this one is running this image, and the transport reuses it instead of loading it again.")
    lines.append ("")
    lines.append ("#define ARTYZ7_PS_APP_CRC32 0x%08XU" % (zlib.crc32 (img) & 0xFFFFFFFF))
    lines.append ("")
    lines.append ("static const uint8_t ARTYZ7_PS_APP[ARTYZ7_PS_APP_SIZE] =")
    lines.append ("{")

    for off in range (0, len (img), 12):
        chunk = img[off:off + 12]

        lines.append ("  " + " ".join ("0x%02X," % b for b in chunk))

    lines.append ("};")
    lines.append ("")
    lines.append ("#endif // HC_ARTYZ7_PS_APP_H")
    lines.append ("")

    with open (dst, "w") as f:
        f.write ("\n".join (lines))

    print ("  %s: %u bytes from %s" % (os.path.basename (dst), len (img), os.path.basename (src)))

    return 0

if __name__ == "__main__":
    sys.exit (main ())
