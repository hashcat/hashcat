import re
import sys

SECTIONS = ["mio", "pll", "clock", "peripherals"]

REVISION = "3_0"

def parse (path):
    src = open (path).read ()

    ops = []

    for section in SECTIONS:
        name = f"ps7_{section}_init_data_{REVISION}"

        m = re.search (r"^proc\s+" + name + r"\s*\{\}\s*\{(.*?)^\}", src, re.S | re.M)

        if m is None:
            sys.exit (f"{path}: no proc {name}")

        body = m.group (1)

        ops.append (("section", section, 0, 0))

        NUM = r"(0[xX][0-9a-fA-F]+|[0-9]+)"

        for line in body.splitlines ():
            line = line.strip ()

            if line == "":      continue
            if line[0] == "#":  continue

            w = re.match (r"^mwr\s+(?:-force\s+)?" + NUM + r"\s+" + NUM + r"$", line)

            if w is not None:
                ops.append (("write", int (w.group (1), 0), 0xFFFFFFFF, int (w.group (2), 0)))

                continue

            k = re.match (r"^mask_write\s+" + NUM + r"\s+" + NUM + r"\s+" + NUM + r"$", line)

            if k is not None:
                ops.append (("write", int (k.group (1), 0), int (k.group (2), 0), int (k.group (3), 0)))

                continue

            p = re.match (r"^mask_poll\s+" + NUM + r"\s+" + NUM + r"$", line)

            if p is not None:
                ops.append (("poll", int (p.group (1), 0), int (p.group (2), 0), 0))

                continue

            d = re.match (r"^mask_delay\s+" + NUM + r"\s+" + NUM + r"$", line)

            if d is not None:
                ops.append (("delay", 0, 0, int (d.group (2), 0)))

                continue

            sys.exit (f"{path}: unrecognised line in {name}: {line!r}")

    return ops

def main ():
    if len (sys.argv) < 2:
        sys.exit ("usage: gen_ps7_init.py <ps7_init.tcl>")

    ops = parse (sys.argv[1])

    n = len ([o for o in ops if o[0] != "section"])

    print ("/**")
    print (" * Author......: See docs/credits.txt")
    print (" * License.....: MIT")
    print (" */")
    print ("//")
    print ("// GENERATED by src/fpga/bcrypt/ps_app/gen_ps7_init.py from Vivado's ps7_init.tcl.")
    print ("// DO NOT EDIT. Regenerate it if the board preset changes.")
    print ("//")
    print ("// The clock, PLL and MIO setup an FSBL would normally do, as data. hashcat replays this over")
    print ("// JTAG before it loads anything, because none of the PS peripherals, and in particular none of")
    print ("// the Ethernet path, works until it has run.")
    print ("//")
    print ("// The DDR section is NOT here. The application runs from on-chip memory, so DDR is never")
    print ("// initialised, and leaving it out removes 82 of the 219 operations Vivado generates.")
    print ("")
    print ("#ifndef HC_ARTYZ7_PS7_INIT_H")
    print ("#define HC_ARTYZ7_PS7_INIT_H")
    print ("")
    print ("#define PS7_OP_WRITE  0")
    print ("#define PS7_OP_POLL   1")
    print ("#define PS7_OP_DELAY  2")
    print ("")
    print ("typedef struct ps7_op")
    print ("{")
    print ("  unsigned char  op;")
    print ("  unsigned int   addr;")
    print ("  unsigned int   mask;")
    print ("  unsigned int   val;")
    print ("")
    print ("} ps7_op_t;")
    print ("")
    print (f"#define PS7_INIT_OPS {n}")
    print ("")
    print ("static const ps7_op_t PS7_INIT[PS7_INIT_OPS] =")
    print ("{")

    for kind, a, m, v in ops:
        if kind == "section":
            print (f"  // ---- {a} ----")

            continue

        if kind == "write":
            print (f"  {{ PS7_OP_WRITE, 0x{a:08X}, 0x{m:08X}, 0x{v:08X} }},")
        elif kind == "poll":
            print (f"  {{ PS7_OP_POLL,  0x{a:08X}, 0x{m:08X}, 0x00000000 }},")
        else:
            print (f"  {{ PS7_OP_DELAY, 0x00000000, 0x00000000, 0x{v:08X} }},")

    print ("};")
    print ("")
    print ("#endif")

if __name__ == "__main__":
    main ()
